using System.Text.Json;

namespace KillerBench.Engine.BitLocker;

public enum BitLockerNewProtector { Tpm, RecoveryPassword }

public sealed record BitLockerProtectorCreationState(string Volume, string Identity, string VolumeStatus, string LockStatus,
    bool OperatingSystemVolume, bool TpmPresent, bool TpmReady, IReadOnlyList<BitLockerProtector> Protectors, bool Complete);

public enum BitLockerProtectorCreationOutcome { Preview, Blocked, Verified, NotApplied, Failed, Uncertain, Stopped }

public sealed record BitLockerProtectorCreationResult(string Volume, BitLockerNewProtector Kind, BitLockerProtectorCreationOutcome Outcome,
    string Detail, BitLockerProtectorCreationState? Before = null, ToolResult? Command = null,
    BitLockerProtectorCreationState? After = null, Guid? Created = null, string? JournalPath = null)
{
    public string Machine { get; init; } = Environment.MachineName;
    public int GetExitCode() => Outcome switch
    {
        BitLockerProtectorCreationOutcome.Preview or BitLockerProtectorCreationOutcome.Verified => 0,
        BitLockerProtectorCreationOutcome.Stopped => 130,
        _ => 3
    };
}

public interface IBitLockerProtectorCreationHost
{
    bool IsAdministrator { get; }
    Task<RestartSnapshot> ReadRestartAsync(CancellationToken token);
    Task<BitLockerProtectorCreationState> InspectAsync(string volume, CancellationToken token);
    /// <summary>Adds one protector. The recovery password is generated by Windows and must never appear in the returned output.</summary>
    Task<ToolResult> AddAsync(string volume, BitLockerNewProtector kind, CancellationToken token);
}

/// <summary>Adds one TPM or recovery-password protector to an exact volume. A durable pending record prevents a second request until the first is reconciled, so an interruption can never leave extra protectors.</summary>
public static class BitLockerProtectorCreation
{
    private static readonly string[] TpmTypes = ["Tpm", "TpmPin", "TpmStartupKey", "TpmPinStartupKey"];
    private static readonly JsonSerializerOptions StrictJson = new(Capture.JsonOptions)
    {
        UnmappedMemberHandling = System.Text.Json.Serialization.JsonUnmappedMemberHandling.Disallow,
        RespectRequiredConstructorParameters = true
    };
    private sealed record PendingRecord(int Schema, string Machine, DateTimeOffset StartedUtc, string Volume,
        BitLockerNewProtector Kind, BitLockerProtectorCreationState Before, ToolResult? Command);

    public static string NormalizeVolume(string volume) => BitLockerProtectionResume.NormalizeVolume(volume);

    public static BitLockerProtectorCreationResult Preview(string volume, BitLockerNewProtector kind)
    {
        volume = NormalizeVolume(volume);
        if (!Enum.IsDefined(kind)) throw new ArgumentException("Unrecognized protector type.");
        return new(volume, kind, BitLockerProtectorCreationOutcome.Preview, kind == BitLockerNewProtector.Tpm
            ? "Preview only. Execution will require the unlocked operating-system volume, a ready TPM, no existing TPM-based protector, clear restart evidence and administrator access, save a pending record, add one TPM protector, then verify exactly one new TPM protector beside every prior protector. Encryption, policy and recovery backups are not changed."
            : "Preview only. Execution will require the unlocked volume, no existing recovery password, clear restart evidence and administrator access, save a pending record, add one recovery password, then verify exactly one new recovery-password protector beside every prior protector. The password is never shown or logged; back it up to a file, Active Directory or Microsoft Entra ID afterwards.");
    }

    public static async Task<BitLockerProtectorCreationResult> RunAsync(string volume, BitLockerNewProtector kind, bool execute,
        string journalFolder, IBitLockerProtectorCreationHost host, IProgress<string>? progress = null, TimeSpan? operationTimeout = null,
        CancellationToken token = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(journalFolder);
        ArgumentNullException.ThrowIfNull(host);
        volume = NormalizeVolume(volume);
        token.ThrowIfCancellationRequested();
        if (!execute) return Preview(volume, kind);
        TimeSpan limit = operationTimeout ?? TimeSpan.FromMinutes(2);
        if (limit <= TimeSpan.Zero || limit > TimeSpan.FromMinutes(10)) throw new ArgumentOutOfRangeException(nameof(operationTimeout));

        string root = Path.GetFullPath(journalFolder);
        Directory.CreateDirectory(root);
        using var gate = new FileStream(Path.Combine(root, "bitlocker-protector.lock"), FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.None);
        string pendingPath = Path.Combine(root, "bitlocker-protector.pending.json");
        if (File.Exists(pendingPath))
            return new(volume, kind, BitLockerProtectorCreationOutcome.Blocked,
                "A prior protector request needs reconciliation before another can start.", JournalPath: pendingPath);

        Report(progress, "Inspecting " + volume + ", its protectors and the TPM.");
        BitLockerProtectorCreationState before;
        try { before = await Required(ct => host.InspectAsync(volume, ct), "Protector inspection", TimeSpan.FromSeconds(45), token: token).ConfigureAwait(false); }
        catch (Exception error) when (!token.IsCancellationRequested && Unavailable(error))
        { return new(volume, kind, BitLockerProtectorCreationOutcome.Blocked, "Protector eligibility could not be established: " + error.Message); }
        if (EligibilityBlocker(volume, kind, before) is { } blocker) return new(volume, kind, BitLockerProtectorCreationOutcome.Blocked, blocker, before);
        RestartSnapshot restart;
        try { restart = await Required(host.ReadRestartAsync, "Restart inspection", TimeSpan.FromSeconds(20), token: token).ConfigureAwait(false); }
        catch (Exception error) when (!token.IsCancellationRequested && Unavailable(error))
        { return new(volume, kind, BitLockerProtectorCreationOutcome.Blocked, "Restart readiness could not be established: " + error.Message, before); }
        if (RestartDiagnostics.Assess(restart) is { State: not CheckState.Clear } restartCheck)
            return new(volume, kind, BitLockerProtectorCreationOutcome.Blocked, "Restart readiness must be clear before a protector is added. " + restartCheck.Detail, before);
        if (!host.IsAdministrator)
            return new(volume, kind, BitLockerProtectorCreationOutcome.Blocked, "Administrator access is required. No protector was added.", before);

        var pending = new PendingRecord(1, Environment.MachineName, DateTimeOffset.UtcNow, volume, kind, before, null);
        await JournalPersistence.WriteAsync(pendingPath, JsonSerializer.Serialize(pending, Capture.JsonOptions), token: token).ConfigureAwait(false);
        string journalPath = Path.Combine(root, "bitlocker-protector-" + Guid.NewGuid().ToString("N") + ".json");
        ToolResult? command = null;
        bool dispatched = false;
        BitLockerProtectorCreationResult result;
        try
        {
            Report(progress, "Repeating protector, TPM and restart checks immediately before the request.");
            var fresh = await Required(ct => host.InspectAsync(volume, ct), "Final protector inspection", TimeSpan.FromSeconds(45), token: token).ConfigureAwait(false);
            var freshRestart = await Required(host.ReadRestartAsync, "Final restart inspection", TimeSpan.FromSeconds(20), token: token).ConfigureAwait(false);
            if (EligibilityBlocker(volume, kind, fresh) is not null || !SameIdentity(before, fresh) ||
                RestartDiagnostics.Assess(freshRestart).State != CheckState.Clear || !host.IsAdministrator)
            {
                result = new(volume, kind, BitLockerProtectorCreationOutcome.Blocked,
                    "Final volume, protector, TPM, restart or administrator evidence no longer authorizes adding a protector. No request was sent.",
                    before, After: fresh, JournalPath: journalPath);
                await JournalPersistence.WriteAsync(journalPath, JsonSerializer.Serialize(result, Capture.JsonOptions), token: CancellationToken.None).ConfigureAwait(false);
                File.Move(pendingPath, journalPath + ".prepared.json");
                Report(progress, result.Detail);
                return result;
            }
            Report(progress, "Adding one " + Name(kind) + " protector to " + volume + ".");
            dispatched = true;
            command = await Required(ct => host.AddAsync(volume, kind, ct), "Protector creation", limit, token: token).ConfigureAwait(false);
            await JournalPersistence.WriteAsync(pendingPath, JsonSerializer.Serialize(pending with { Command = command }, Capture.JsonOptions), token: CancellationToken.None).ConfigureAwait(false);
            result = await VerifyAsync(volume, kind, before, command, journalPath, host, progress, token).ConfigureAwait(false);
        }
        catch (OperationCanceledException)
        {
            result = new(volume, kind, BitLockerProtectorCreationOutcome.Stopped,
                dispatched ? "The request stopped after it may have reached Windows. Reconcile before adding another protector."
                    : "The final check was canceled before any request was sent. No protector was added.", before, command, JournalPath: journalPath);
        }
        catch (Exception error) when (Unavailable(error))
        {
            result = new(volume, kind, dispatched ? BitLockerProtectorCreationOutcome.Uncertain : BitLockerProtectorCreationOutcome.Blocked,
                dispatched ? "The request was interrupted: " + error.Message + ". Reconcile before adding another protector."
                    : "Final eligibility was unavailable: " + error.Message + ". No request was sent.", before, command, JournalPath: journalPath);
        }
        await JournalPersistence.WriteAsync(journalPath, JsonSerializer.Serialize(result, Capture.JsonOptions), token: CancellationToken.None).ConfigureAwait(false);
        if (!dispatched || result.Outcome is BitLockerProtectorCreationOutcome.Verified or BitLockerProtectorCreationOutcome.NotApplied or BitLockerProtectorCreationOutcome.Failed)
            File.Move(pendingPath, journalPath + ".prepared.json");
        Report(progress, result.Detail);
        return result;
    }

    public static async Task<BitLockerProtectorCreationResult> ReconcileAsync(string journalFolder, IBitLockerProtectorCreationHost host,
        IProgress<string>? progress = null, CancellationToken token = default)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(journalFolder);
        ArgumentNullException.ThrowIfNull(host);
        string root = Path.GetFullPath(journalFolder);
        string pendingPath = Path.Combine(root, "bitlocker-protector.pending.json");
        if (!File.Exists(pendingPath))
            return new("C:", BitLockerNewProtector.RecoveryPassword, BitLockerProtectorCreationOutcome.Blocked, "No pending protector request was found.");
        using var gate = new FileStream(Path.Combine(root, "bitlocker-protector.lock"), FileMode.OpenOrCreate, FileAccess.ReadWrite, FileShare.None);
        PendingRecord pending;
        try { pending = await ReadPendingAsync(pendingPath, token).ConfigureAwait(false); }
        catch (OperationCanceledException) { throw; }
        catch (Exception error) when (Unavailable(error))
        {
            return new("C:", BitLockerNewProtector.RecoveryPassword, BitLockerProtectorCreationOutcome.Uncertain,
                "The interrupted protector record could not be verified for this computer. It was retained and the request was not repeated.", JournalPath: pendingPath);
        }
        string journalPath = Path.Combine(root, "bitlocker-protector-recovered-" + Guid.NewGuid().ToString("N") + ".json");
        var result = await VerifyAsync(pending.Volume, pending.Kind, pending.Before, pending.Command, journalPath, host, progress, token).ConfigureAwait(false);
        await JournalPersistence.WriteAsync(journalPath, JsonSerializer.Serialize(result, Capture.JsonOptions), token: CancellationToken.None).ConfigureAwait(false);
        if (result.Outcome is BitLockerProtectorCreationOutcome.Verified or BitLockerProtectorCreationOutcome.NotApplied)
            File.Move(pendingPath, journalPath + ".prepared.json");
        return result;
    }

    public static string? EligibilityBlocker(string volume, BitLockerNewProtector kind, BitLockerProtectorCreationState state)
    {
        volume = NormalizeVolume(volume);
        if (!Enum.IsDefined(kind)) return "Unrecognized protector type.";
        if (!state.Complete || !string.Equals(volume, state.Volume, StringComparison.OrdinalIgnoreCase))
            return "A complete exact selected-volume inventory is required. No protector was added.";
        if (string.IsNullOrWhiteSpace(state.Identity) || state.Identity.Length > 512 || state.Identity.Any(char.IsControl))
            return "The exact selected volume identity could not be confirmed. No protector was added.";
        if (state.LockStatus != "Unlocked") return "The selected volume must be unlocked. No protector was added.";
        if (state.VolumeStatus is "DecryptionInProgress" or "DecryptionPaused")
            return "Decryption is in progress. Let it finish or resume encryption before adding protectors.";
        if (state.Protectors.Count > 63 || state.Protectors.Select(p => p.Id).Distinct().Count() != state.Protectors.Count || state.Protectors.Any(p => p.Id == Guid.Empty))
            return "A complete unique protector identity set is required. No protector was added.";
        if (kind == BitLockerNewProtector.Tpm)
        {
            if (!state.OperatingSystemVolume) return "A TPM protector applies only to the operating-system volume.";
            if (!state.TpmPresent || !state.TpmReady) return "The TPM must be present and ready. Prepare it in the firmware or with the TPM management console first.";
            if (state.Protectors.Any(p => TpmTypes.Contains(p.Type, StringComparer.Ordinal))) return "This volume already has a TPM-based protector. Windows allows only one.";
        }
        else if (state.Protectors.Any(p => p.Type == "RecoveryPassword"))
            return "This volume already has a recovery password. Back up that one instead of adding another.";
        return null;
    }

    private static async Task<BitLockerProtectorCreationResult> VerifyAsync(string volume, BitLockerNewProtector kind,
        BitLockerProtectorCreationState before, ToolResult? command, string journalPath, IBitLockerProtectorCreationHost host,
        IProgress<string>? progress, CancellationToken token)
    {
        Report(progress, "Verifying the protector set on " + volume + ".");
        BitLockerProtectorCreationState after;
        try { after = await Required(ct => host.InspectAsync(volume, ct), "Protector verification", TimeSpan.FromSeconds(45), token: token).ConfigureAwait(false); }
        catch (Exception error) when (!token.IsCancellationRequested && Unavailable(error))
        { return new(volume, kind, BitLockerProtectorCreationOutcome.Uncertain, "Verification was unavailable: " + error.Message, before, command, JournalPath: journalPath); }
        if (!after.Complete || !string.Equals(before.Identity, after.Identity, StringComparison.Ordinal))
            return new(volume, kind, BitLockerProtectorCreationOutcome.Uncertain, "The selected volume identity could not be confirmed during verification.", before, command, after, JournalPath: journalPath);
        var prior = before.Protectors.Select(Key).ToHashSet(StringComparer.Ordinal);
        bool priorKept = prior.All(key => after.Protectors.Select(Key).Contains(key, StringComparer.Ordinal));
        var added = after.Protectors.Where(p => !prior.Contains(Key(p))).ToList();
        string type = kind == BitLockerNewProtector.Tpm ? "Tpm" : "RecoveryPassword";
        bool commandComplete = command is not null && command.ExitCode == 0 && !command.TimedOut && !command.Truncated && string.IsNullOrWhiteSpace(command.Error);
        if (priorKept && added.Count == 1 && added[0].Type == type)
            return new(volume, kind, BitLockerProtectorCreationOutcome.Verified,
                "Exactly one new " + Name(kind) + " protector is present and every prior protector remains." +
                (kind == BitLockerNewProtector.RecoveryPassword ? " Back up this recovery password now; it has not been saved anywhere yet." : " Boot unlock with it is not tested."),
                before, command, after, added[0].Id, journalPath);
        if (priorKept && added.Count == 0)
            return new(volume, kind, commandComplete ? BitLockerProtectorCreationOutcome.NotApplied : BitLockerProtectorCreationOutcome.Failed,
                commandComplete ? "Windows completed the request, but no new protector appeared. The request was not repeated."
                    : "The request failed and the protector set is unchanged. The request was not repeated.", before, command, after, JournalPath: journalPath);
        return new(volume, kind, BitLockerProtectorCreationOutcome.Uncertain,
            "The protector set changed in an unexpected way. Review it before any further change.", before, command, after, JournalPath: journalPath);
    }

    private static string Key(BitLockerProtector protector) => protector.Id.ToString("D") + "|" + protector.Type;
    private static bool SameIdentity(BitLockerProtectorCreationState left, BitLockerProtectorCreationState right) => right.Complete &&
        string.Equals(left.Identity, right.Identity, StringComparison.Ordinal) &&
        left.Protectors.Select(Key).Order(StringComparer.Ordinal).SequenceEqual(right.Protectors.Select(Key).Order(StringComparer.Ordinal));
    private static string Name(BitLockerNewProtector kind) => kind == BitLockerNewProtector.Tpm ? "TPM" : "recovery-password";

    private static async Task<PendingRecord> ReadPendingAsync(string path, CancellationToken token)
    {
        await using var stream = new FileStream(path, FileMode.Open, FileAccess.Read, FileShare.Read, 4096, FileOptions.Asynchronous);
        if (stream.Length is <= 0 or > 65_536) throw new InvalidDataException("Pending protector record size is invalid.");
        var bytes = new byte[checked((int)stream.Length)];
        await stream.ReadExactlyAsync(bytes, token).ConfigureAwait(false);
        try
        {
            var pending = JsonSerializer.Deserialize<PendingRecord>(bytes, StrictJson) ?? throw new InvalidDataException("Pending protector record is empty.");
            if (pending.Schema != 1 || !pending.Machine.Equals(Environment.MachineName, StringComparison.OrdinalIgnoreCase) || pending.StartedUtc == default ||
                NormalizeVolume(pending.Volume) != pending.Volume || !Enum.IsDefined(pending.Kind) || !pending.Before.Complete)
                throw new InvalidDataException("Pending protector record contains invalid evidence.");
            return pending;
        }
        catch (JsonException error) { throw new InvalidDataException("Pending protector record is invalid.", error); }
        catch (ArgumentException error) { throw new InvalidDataException("Pending protector record contains an invalid volume.", error); }
    }

    private static bool Unavailable(Exception error) => error is IOException or InvalidDataException or UnauthorizedAccessException or
        InvalidOperationException or NotSupportedException or TimeoutException or System.ComponentModel.Win32Exception or
        System.Security.SecurityException or OperationCanceledException;
    private static async Task<T> Required<T>(Func<CancellationToken, Task<T>> operation, string name, TimeSpan limit, CancellationToken token)
    {
        var pending = operation(token) ?? throw new InvalidOperationException(name + " provider returned no task.");
        return await pending.WaitAsync(limit, token).ConfigureAwait(false) ?? throw new InvalidDataException(name + " provider returned no evidence.");
    }
    private static void Report(IProgress<string>? progress, string message)
    {
        try { progress?.Report(message); }
        catch (Exception error) when (error is not OutOfMemoryException and not StackOverflowException) { }
    }
}

public sealed class WindowsBitLockerProtectorCreationHost : IBitLockerProtectorCreationHost
{
    public bool IsAdministrator => WindowsState.IsAdministrator();

    public Task<RestartSnapshot> ReadRestartAsync(CancellationToken token)
    {
        token.ThrowIfCancellationRequested();
        return Task.FromResult(RestartDiagnostics.Read());
    }

    public async Task<BitLockerProtectorCreationState> InspectAsync(string volume, CancellationToken token)
    {
        volume = BitLockerProtectorCreation.NormalizeVolume(volume);
        string command = "$ErrorActionPreference='Stop';$ProgressPreference='SilentlyContinue';" +
            "$b=Get-BitLockerVolume -MountPoint '" + volume + "' -ErrorAction Stop;" +
            "$v=Get-Volume -DriveLetter '" + volume[0] + "' -ErrorAction Stop;" +
            "$t=Get-Tpm -ErrorAction Stop;" +
            "[pscustomobject]@{volume=[string]$b.MountPoint;identity=[string]$v.UniqueId;volumeStatus=[string]$b.VolumeStatus;lockStatus=[string]$b.LockStatus;" +
            "operatingSystem=([string]$b.VolumeType -eq 'OperatingSystem');tpmPresent=[bool]$t.TpmPresent;tpmReady=[bool]$t.TpmReady;" +
            "protectors=@($b.KeyProtector | ForEach-Object {[pscustomobject]@{id=[string]$_.KeyProtectorId;type=[string]$_.KeyProtectorType}})} | ConvertTo-Json -Depth 4 -Compress";
        var result = await BoundedTool.RunAsync(new RepairStep(PrintRecovery.Tool,
            ["-NoLogo", "-NoProfile", "-NonInteractive", "-Command", command], true), TimeSpan.FromSeconds(45), token: token).ConfigureAwait(false);
        return Interpret(result, volume);
    }

    public Task<ToolResult> AddAsync(string volume, BitLockerNewProtector kind, CancellationToken token)
    {
        volume = BitLockerProtectorCreation.NormalizeVolume(volume);
        string option = kind == BitLockerNewProtector.Tpm ? "-TpmProtector" : "-RecoveryPasswordProtector";
        string command = "$ErrorActionPreference='Stop';$ProgressPreference='SilentlyContinue';$WarningPreference='SilentlyContinue';" +
            "Add-BitLockerKeyProtector -MountPoint '" + volume + "' " + option + " -ErrorAction Stop | Out-Null";
        return BoundedTool.RunAsync(new RepairStep(PrintRecovery.Tool,
            ["-NoLogo", "-NoProfile", "-NonInteractive", "-Command", command], false), TimeSpan.FromMinutes(2), token: token);
    }

    public static BitLockerProtectorCreationState Interpret(ToolResult result, string volume)
    {
        volume = BitLockerProtectorCreation.NormalizeVolume(volume);
        BitLockerProtectorCreationState Unknown() => new(volume, "", "", "", false, false, false, [], false);
        if (result.ExitCode != 0 || result.TimedOut || result.Truncated || !string.IsNullOrWhiteSpace(result.Error)) return Unknown();
        try
        {
            using var document = JsonDocument.Parse(result.Output);
            JsonElement root = document.RootElement;
            string[] expected = ["volume", "identity", "volumeStatus", "lockStatus", "operatingSystem", "tpmPresent", "tpmReady", "protectors"];
            string[] flags = ["operatingSystem", "tpmPresent", "tpmReady"];
            if (root.ValueKind != JsonValueKind.Object || root.EnumerateObject().Count() != expected.Length ||
                !expected.All(name => root.TryGetProperty(name, out _)) ||
                flags.Any(name => root.GetProperty(name).ValueKind is not (JsonValueKind.True or JsonValueKind.False))) return Unknown();
            string? identity = root.GetProperty("identity").GetString();
            string? status = root.GetProperty("volumeStatus").GetString();
            string? lockStatus = root.GetProperty("lockStatus").GetString();
            JsonElement items = root.GetProperty("protectors");
            if (!string.Equals(root.GetProperty("volume").GetString(), volume, StringComparison.OrdinalIgnoreCase) ||
                string.IsNullOrWhiteSpace(identity) || identity.Length > 512 || identity.Any(char.IsControl) ||
                status is not ("FullyDecrypted" or "FullyEncrypted" or "EncryptionInProgress" or "DecryptionInProgress" or "EncryptionPaused" or "DecryptionPaused") ||
                lockStatus is not ("Locked" or "Unlocked") || items.ValueKind != JsonValueKind.Array || items.GetArrayLength() > 64) return Unknown();
            var protectors = new List<BitLockerProtector>();
            foreach (JsonElement item in items.EnumerateArray())
            {
                if (item.ValueKind != JsonValueKind.Object || item.EnumerateObject().Count() != 2 ||
                    !Guid.TryParse(item.GetProperty("id").GetString(), out Guid id) || id == Guid.Empty || protectors.Any(p => p.Id == id)) return Unknown();
                string? type = item.GetProperty("type").GetString();
                if (string.IsNullOrWhiteSpace(type) || type.Length > 64 || type.Any(char.IsControl)) return Unknown();
                protectors.Add(new(id, type));
            }
            return new(volume, identity, status, lockStatus, root.GetProperty("operatingSystem").GetBoolean(),
                root.GetProperty("tpmPresent").GetBoolean(), root.GetProperty("tpmReady").GetBoolean(), protectors.AsReadOnly(), true);
        }
        catch (Exception error) when (error is JsonException or InvalidOperationException or KeyNotFoundException or FormatException)
        { return Unknown(); }
    }
}
